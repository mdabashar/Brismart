"""Write supabase/seed.sql from products.js plus the extra items in data.js.

Usage: python tools/make_seed.py <web_dir>
"""
import json
import re
import sys
from pathlib import Path

web = Path(sys.argv[1])


def js_array(text, name):
    body = re.search(rf"const {name} = \[(.*?)\n\];", text, re.S).group(1)
    return [json.loads(line.strip().rstrip(",")) for line in body.splitlines() if line.strip().startswith("{")]


rows = js_array((web / "products.js").read_text(encoding="utf-8"), "HB_PRODUCTS")
rows += js_array((web / "data.js").read_text(encoding="utf-8"), "EXTRA_PRODUCTS")


def q(v):
    if v is None:
        return "null"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


cols = ["id", "cat", "name", "bn", "brand", "size", "price", "price_max", "price_unit", "img", "icon", "note"]
values = []
for r in rows:
    rec = {"id": r["id"], "cat": r["cat"], "name": r["name"], "bn": r.get("bn"), "brand": r.get("brand"),
           "size": r.get("size", "each"), "price": r["price"], "price_max": r.get("max"),
           "price_unit": r.get("unit"), "img": r.get("img"), "icon": r.get("icon"), "note": r.get("note")}
    values.append("(" + ", ".join(q(rec[c]) for c in cols) + ")")

sql = (
    "-- Brismart product catalogue (generated by tools/make_seed.py). Run after schema.sql.\n"
    "-- Safe to re-run: existing products with the same id are updated.\n"
    f"insert into public.products ({', '.join(cols)}) values\n"
    + ",\n".join(values)
    + "\non conflict (id) do update set " + ", ".join(f"{c} = excluded.{c}" for c in cols[1:]) + ";\n"
)
(web / "supabase" / "seed.sql").write_text(sql, encoding="utf-8")
print("seed rows", len(rows))
