-- Brismart online store: database schema for Supabase.
-- Run once in the Supabase dashboard: SQL Editor -> New query -> paste -> Run.
-- Then run seed.sql to load the product catalogue.

-- ---------- Staff (admin) accounts ----------
-- Only users listed here can change products, even if someone else signs up.
create table if not exists public.admins (
  user_id uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.admins enable row level security;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.admins where user_id = auth.uid());
$$;

drop policy if exists "admins can see admin list" on public.admins;
create policy "admins can see admin list" on public.admins
  for select to authenticated using (public.is_admin());

-- ---------- Products ----------
create table if not exists public.products (
  id          bigint generated by default as identity (start with 10000) primary key,
  cat         text not null,                       -- category id, e.g. 'fish' (see data.js)
  name        text not null,
  bn          text,                                -- Bengali name
  brand       text,
  size        text not null default 'each',
  price       numeric(10, 2) not null check (price >= 0),
  price_max   numeric(10, 2) check (price_max is null or price_max >= price),  -- set for a price range
  price_unit  text,                                -- e.g. 'kg' when sold by weight
  img         text,                                -- image URL or site-relative path
  icon        text,                                -- emoji shown when there is no image
  note        text,                                -- extra detail on the product page
  active      boolean not null default true,       -- false = hidden from customers
  updated_at  timestamptz not null default now()
);

create or replace function public.touch_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists products_touch on public.products;
create trigger products_touch before update on public.products
  for each row execute function public.touch_updated_at();

alter table public.products enable row level security;

drop policy if exists "anyone can read active products" on public.products;
create policy "anyone can read active products" on public.products
  for select using (active or public.is_admin());

drop policy if exists "admins can add products" on public.products;
create policy "admins can add products" on public.products
  for insert to authenticated with check (public.is_admin());

drop policy if exists "admins can edit products" on public.products;
create policy "admins can edit products" on public.products
  for update to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "admins can delete products" on public.products;
create policy "admins can delete products" on public.products
  for delete to authenticated using (public.is_admin());

-- ---------- Product photos ----------
insert into storage.buckets (id, name, public)
values ('product-images', 'product-images', true)
on conflict (id) do nothing;

drop policy if exists "admins can upload product images" on storage.objects;
create policy "admins can upload product images" on storage.objects
  for insert to authenticated with check (bucket_id = 'product-images' and public.is_admin());

drop policy if exists "admins can replace product images" on storage.objects;
create policy "admins can replace product images" on storage.objects
  for update to authenticated using (bucket_id = 'product-images' and public.is_admin());

drop policy if exists "admins can remove product images" on storage.objects;
create policy "admins can remove product images" on storage.objects
  for delete to authenticated using (bucket_id = 'product-images' and public.is_admin());

